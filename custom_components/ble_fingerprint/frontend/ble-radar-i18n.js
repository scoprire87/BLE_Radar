export function language(hass) {
  const lang = (hass?.locale?.language || hass?.language || navigator.language || "en").toLowerCase();
  const short = lang.split("-")[0];
  return STRINGS[lang] ? lang : STRINGS[short] ? short : "en";
}

// Returns a translate function for the user's language:
// t("msg.room_saved", { room: "Kitchen" })
export function translator(hass) {
  const strings = STRINGS[language(hass)];
  return (key, vars = {}) => {
    const text = strings[key] ?? STRINGS.en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (_m, name) => (vars[name] ?? `{${name}}`));
  };
}

// Label of a guided calibration point
export function pointLabel(t, point) {
  if (point.kind === "center") return t("point.center");
  if (point.kind === "corner") return t("point.corner", { n: point.index });
  return t("point.free");
}
